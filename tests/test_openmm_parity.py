"""
Format-independent regression test for the GB1 molten-globule (mg) model.

The classic regression test (``run_tests.py``) compares output *files* line by
line.  That cannot survive the move from GROMACS text files to the OpenMM
parameter file, so this test compares *physics* instead:

    reference : tests/test_outputs/gpref/case_1/ (GROMACS files, frozen)
                loaded into OpenMM with GROMACS-equivalent settings
    candidate : the model freshly generated by the current code, turned into
                an OpenMM System by ``build_candidate_system``

The two Systems are compared at two complementary levels:

* parameters (``multiego.omm.parameters``): every bond, angle, dihedral and
  pair, the effective (c6, c12) of every atom pair and the exclusions must
  match to 1e-5 relative (the precision of the GROMACS text files).  This
  catches a wrong value even in a single one of ~120,000 LJ pairs;
* physics (``multiego.omm.energy``): on several configurations of GB1 the
  energy and per-atom forces of every term must agree.  This catches what
  parameters cannot: wrong functional forms, cut-off, potential shift, PBC.  The candidate is built with the native OpenMM
backend (``mego_params.h5`` + ``multiego.omm.builder``), so this test checks
that the OpenMM backend reproduces the GROMACS model.

A second, independent safeguard pins the reference energies themselves
(``openmm_reference_energies.json``), so that a change in the reference
loader or in OpenMM would be noticed too.  To regenerate that file run::

    python tests/test_openmm_parity.py --update
"""

import glob
import json
import os
import shutil
import subprocess
import sys

import numpy as np
import pytest

TEST_ROOT = os.path.dirname(os.path.abspath(__file__))
MEGO_ROOT = os.path.abspath(os.path.join(TEST_ROOT, os.pardir))
sys.path.insert(0, os.path.join(MEGO_ROOT, "src"))

import openmm.app as app  # noqa: E402

from multiego.omm import builder, energy, paramfile, parameters  # noqa: E402
from multiego.omm.gromacs_reference import load_gromacs_system  # noqa: E402

SYSTEM = "gpref"
REFERENCE_DIR = os.path.join(TEST_ROOT, "test_outputs", SYSTEM, "case_1")
GRO_FILE = os.path.join(TEST_ROOT, "test_inputs", SYSTEM, "gb1_mego.gro")
PINNED_ENERGIES = os.path.join(REFERENCE_DIR, "openmm_reference_energies.json")

# Name used for the freshly generated output (outputs/gpref/parity_1).
CANDIDATE_NAME = "parity"
# --backend openmm: only the parameter file is needed (and it is faster).
MG_COMMAND = [
    "--system",
    SYSTEM,
    "--egos",
    "mg",
    "--no_header",
    "--explicit_name",
    CANDIDATE_NAME,
    "--backend",
    "openmm",
]

# Random displacement (nm) used to create extra test configurations.  The
# .gro file alone probes a single set of distances; displaced copies probe
# different distances for every term while staying physically reasonable.
DISPLACEMENT = 0.02
N_DISPLACED = 2


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def generate_candidate():
    """Run multi-eGO (mg) for GB1 and return the output directory."""
    for old in glob.glob(os.path.join(MEGO_ROOT, "outputs", SYSTEM, f"{CANDIDATE_NAME}_*")):
        shutil.rmtree(old)
    cmd = [sys.executable, os.path.join(MEGO_ROOT, "multiego.py"), *MG_COMMAND]
    cmd += ["--inputs_dir", os.path.join(TEST_ROOT, "test_inputs")]
    subprocess.run(cmd, check=True, cwd=MEGO_ROOT, stdout=subprocess.DEVNULL)
    return os.path.join(MEGO_ROOT, "outputs", SYSTEM, f"{CANDIDATE_NAME}_1")


def build_candidate_system(output_dir):
    """
    Turn the freshly generated output into an OpenMM System with the native
    builder: parameter file (mego_params.h5) -> multiego.omm.builder.

    The GROMACS files are not used, so the comparison with the (GROMACS)
    reference is a genuine cross-check of the two backends.
    """
    params = paramfile.read(os.path.join(output_dir, paramfile.DEFAULT_FILENAME))
    box = app.GromacsGroFile(GRO_FILE).getPeriodicBoxVectors()
    return builder.create_system(params, box_vectors=box)


def configurations(positions):
    """The .gro configuration plus N_DISPLACED reproducibly displaced copies."""
    x0 = np.array(positions.value_in_unit(positions.unit))
    rng = np.random.default_rng(2024)
    return [x0] + [x0 + rng.normal(0.0, DISPLACEMENT, x0.shape) for _ in range(N_DISPLACED)]


# ---------------------------------------------------------------------------
# Fixtures (computed once per test session)
# ---------------------------------------------------------------------------


@pytest.fixture(scope="module")
def reference():
    system, positions = load_gromacs_system(os.path.join(REFERENCE_DIR, "topol_mego.top"), GRO_FILE)
    confs = configurations(positions)
    return system, confs, [energy.decompose(system, x) for x in confs]


@pytest.fixture(scope="module")
def reference_parameters(reference):
    return parameters.extract(reference[0])


@pytest.fixture(scope="module")
def candidate(reference):
    _, confs, _ = reference
    output_dir = generate_candidate()
    system = build_candidate_system(output_dir)
    yield system, [energy.decompose(system, x) for x in confs]
    shutil.rmtree(output_dir, ignore_errors=True)


# ---------------------------------------------------------------------------
# Tests
# ---------------------------------------------------------------------------


def test_reference_has_expected_terms(reference):
    """The reference must contain every term of an mg model, all non-trivial."""
    _, _, decompositions = reference
    for term in ("bonds", "angles", "proper_dihedrals", "improper_dihedrals", "pairs", "nonbonded"):
        assert term in decompositions[0], f"term {term} missing from the reference"
        assert abs(decompositions[0][term]["energy"]) > 0.0, f"term {term} is zero in the reference"
    # multi-eGO has no charges: electrostatics, if present, must vanish.
    if "electrostatics" in decompositions[0]:
        assert decompositions[0]["electrostatics"]["energy"] == pytest.approx(0.0, abs=1e-10)


def test_reference_energies_are_pinned(reference):
    """Guard against changes of the reference loader / OpenMM itself."""
    _, _, decompositions = reference
    with open(PINNED_ENERGIES) as f:
        pinned = json.load(f)
    for i, decomposition in enumerate(decompositions):
        for term, value in pinned[i].items():
            assert decomposition[term]["energy"] == pytest.approx(
                value, rel=1e-8, abs=1e-8
            ), f"configuration {i}, term {term}"


def test_candidate_parameters_match_reference(reference_parameters, candidate):
    """Every parameter of the freshly generated model must match the reference."""
    failures = parameters.compare(reference_parameters, parameters.extract(candidate[0]))
    assert not failures, "\n".join(failures)


def test_candidate_matches_reference(reference, candidate):
    """Every term of the freshly generated model must match the reference."""
    _, confs, ref_decompositions = reference
    _, cand_decompositions = candidate
    for i, (ref, cand) in enumerate(zip(ref_decompositions, cand_decompositions)):
        failures = energy.compare(ref, cand)
        assert not failures, f"configuration {i}:\n" + "\n".join(failures) + "\n" + energy.format_table(ref, cand)


def test_multiple_copies(tmp_path, candidate):
    """
    Two copies of GB1: checks atom offsets and per-copy exclusions of the
    builder against GROMACS ``[ molecules ] GB1 2`` read by GromacsTopFile.
    """
    # Reference: same files, with two copies in [ molecules ].
    shutil.copy(os.path.join(REFERENCE_DIR, "ffnonbonded.itp"), tmp_path)
    with open(os.path.join(REFERENCE_DIR, "topol_mego.top")) as f:
        top = f.read().rstrip()
    assert top.endswith("1"), "unexpected [ molecules ] section"
    with open(tmp_path / "topol_mego.top", "w") as f:
        f.write(top[:-1] + "2\n")
    # Coordinates: the second copy translated by 10 nm along x (box 23.4 nm).
    with open(GRO_FILE) as f:
        lines = f.read().splitlines()
    n = int(lines[1])
    end = 2 + n
    atoms = lines[2:end]
    shifted = [a[:20] + f"{float(a[20:28]) + 10.0:8.3f}" + a[28:] for a in atoms]
    with open(tmp_path / "two.gro", "w") as f:
        f.write("\n".join([lines[0], str(2 * n)] + atoms + shifted + [lines[2 + n]]) + "\n")

    ref_system, positions = load_gromacs_system(str(tmp_path / "topol_mego.top"), str(tmp_path / "two.gro"))
    params = paramfile.read(
        os.path.join(MEGO_ROOT, "outputs", SYSTEM, f"{CANDIDATE_NAME}_1", paramfile.DEFAULT_FILENAME)
    )
    cand_system = builder.create_system(
        params, molecules=[("GB1", 2)], box_vectors=ref_system.getDefaultPeriodicBoxVectors()
    )
    assert cand_system.getNumParticles() == 2 * n
    failures = parameters.compare(parameters.extract(ref_system), parameters.extract(cand_system))
    failures += energy.compare(energy.decompose(ref_system, positions), energy.decompose(cand_system, positions))
    assert not failures, "\n".join(failures)


# ---------------------------------------------------------------------------
# Regenerate the pinned reference energies
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    if "--update" not in sys.argv:
        sys.exit("usage: python tests/test_openmm_parity.py --update")
    system, positions = load_gromacs_system(os.path.join(REFERENCE_DIR, "topol_mego.top"), GRO_FILE)
    pinned = []
    for x in configurations(positions):
        decomposition = energy.decompose(system, x)
        pinned.append({term: values["energy"] for term, values in decomposition.items()})
        print(energy.format_table(decomposition), "\n")
    with open(PINNED_ENERGIES, "w") as f:
        json.dump(pinned, f, indent=2)
    print(f"written {PINNED_ENERGIES}")
